export function LanguageProvider({ children }: { children: ReactNode }) {
    const [language, setLanguageState] = useState<Language>("en");

    useEffect(() => {
        // ?lang=ja / ?lang=zh in the URL wins over the saved preference,
        // so hreflang alternate URLs open in the right language.
        const fromUrl = new URLSearchParams(window.location.search).get("lang");
        if (isLanguage(fromUrl)) {
            setLanguageState(fromUrl);
            try {
                localStorage.setItem("lang", fromUrl);
            } catch {
                // storage unavailable (private mode etc.) — URL still applies
            }
            return;
        }
        try {
            const stored = localStorage.getItem("lang");
            if (isLanguage(stored)) setLanguageState(stored);
        } catch {
            // ignore
        }
    }, []);

    useEffect(() => {
        document.documentElement.lang = language === "zh" ? "zh-CN" : language;
    }, [language]);

    const setLanguage = (lang: Language) => {
        try {
            localStorage.setItem("lang", lang);
        } catch {
            // ignore
        }
        setLanguageState(lang);
    };

    const t = (key: string): string => {
        const langDict = translations[language] as Record<string, string>;
        return langDict[key] ?? (translations.en as Record<string, string>)[key] ?? key;
    };

    return (
        <LanguageContext.Provider value={{ language, setLanguage, t }}>
            {children}
        </LanguageContext.Provider>
    );
}

export function useLanguage() {
    const context = useContext(LanguageContext);
    if (!context) {
        throw new Error("useLanguage must be used within LanguageProvider");
    }
    return context;
}
